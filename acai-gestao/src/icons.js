/**
 * Substitui todo `<i data-lucide="nome"></i>` dentro de `root` pelo SVG do ícone.
 * Elementos já convertidos são trocados no DOM, então chamadas repetidas
 * não reprocessam os mesmos ícones.
 */
export function renderIcons(root = document) {
  createIcons({
    icons: iconSet,
    nameAttr: 'data-lucide',
    attrs: { 'stroke-width': 1.75, 'aria-hidden': 'true' },
    root,
  })
}
